#!/usr/bin/env bash
# One-time setup of the local Mosquitto test broker:
#   1. test certificates (make-certs.sh)
#   2. random passwords for vigil-device and vigil-app, saved in secrets/local-*.pass
#   3. Mosquitto password file (cloud/mosquitto/passwd)
#   4. secrets/local.env, used by cloud/test-broker.sh
# Safe to run again: it keeps existing certificates and passwords.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SECRETS="$ROOT/secrets"
mkdir -p "$SECRETS"

"$HERE/make-certs.sh" "$@"

for user in vigil-device vigil-app; do
  f="$SECRETS/local-$user.pass"
  [[ -f $f ]] || { openssl rand -base64 18 | tr -d '\n' > "$f"; chmod 600 "$f"; }
done

chmod 600 "$HERE/acl"
rm -f "$HERE/passwd"
touch "$HERE/passwd" && chmod 600 "$HERE/passwd"
mosquitto_passwd -b "$HERE/passwd" vigil-device "$(cat "$SECRETS/local-vigil-device.pass")"
mosquitto_passwd -b "$HERE/passwd" vigil-app    "$(cat "$SECRETS/local-vigil-app.pass")"

cat > "$SECRETS/local.env" <<EOF
# Local Mosquitto test broker (generated by cloud/mosquitto/setup.sh)
NAME=local-mosquitto
HOST=localhost
PORT=8883
CAFILE=$HERE/certs/ca.crt
WRONG_CAFILE=$HERE/certs/wrong-ca.crt
DEVICE_USER=vigil-device
DEVICE_PASS_FILE=$SECRETS/local-vigil-device.pass
APP_USER=vigil-app
APP_PASS_FILE=$SECRETS/local-vigil-app.pass
EOF
chmod 600 "$SECRETS/local.env"

echo
echo "Done. Start the broker with:  cloud/mosquitto/run.sh"
echo "Then test it with:            cloud/test-broker.sh secrets/local.env"
